/* VIEW:
-VIEW SÃO PSEUDO-TABELAS QUE GRAVAM SQL GRANDES PARA 
SEREM EXECUTADOS EM DIVERSAS PARTES DO CODIGO, SEM PRESISAR 
REESSCREVER O SELECT
*/
-- CRIAR UMA VIEW PARA RETORNAR OS FUNCIONARIOS E OS SEUS SUPERMERCADOS
CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADOS AS 
SELECT FUN_CPF AS "CPF",
	   FUN_NOME AS "NOME",
	   FUN_DATA_NASCIMENTO AS "DATA DE NACIMENTO",
       FUN_TELEFONE AS "TELEFONE",
       FUN_EMAIL AS "E-MAIL",
       FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRBALHO",
       FUN_BANCO_AGENCIA AS "BANCO DE AGENCIA",
       FUN_BANCO_CONTA AS "BANCO DE CONTA",
       FUN_DATA_ADMISSAO AS "DATA DE ADMISSÃO",
       FUN_JORNADA_TRABALHO AS "JORNADA DETRABALHO",
       S.SUP_RAZAO_SOCIAL AS "SUPERMERCADO QUE TRABALHA"
FROM FUNCIONARIOS F 
JOIN SUPERMERCADO S ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT *
FROM  VW_FUNCIONARIOS_SUPERMERCADOS
WHERE UPPER(NOME) LIKE '%RAFAEL';

